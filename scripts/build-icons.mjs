const dir = 'node_modules/lucide-static/icons';
const symbols = ICONS.map((name) => {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  return `<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`;
});

const sprite = `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide icons (ISC, lucide.dev) -->${symbols.join('')}</svg>\n`;
writeFileSync('public/icons.svg', sprite);
writeFileSync(
  'src/app/shared/ui/icon/icon-names.ts',
  `// Generated by scripts/build-icons.mjs — do not edit.\nexport const ICON_NAMES = ${JSON.stringify(ICONS, null, 2).replace(/"/g, "'")} as const;\nexport type IconName = (typeof ICON_NAMES)[number];\n`,
);
console.log(`icons.svg: ${ICONS.length} icons, ${sprite.length} bytes`);
